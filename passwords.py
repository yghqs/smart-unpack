"""密码来源 —— **留给使用者的另一个口子**。

现在只有一种来源：**手给**（命令行 `--密码`，或界面上那个框敲）。
工具**不替你管密码、也不从字典炮轰** —— 你给什么它用什么。

想加新来源（例如从环境变量读、从外部程序取、从某个服务拉），**只改这个文件**：
写一个 `从XX(入参)` 返回「密码列表」，然后在 `合并()` 的调用处加进去即可，别处不用动。

约定：
  · 每个来源返回一个**有序列表**；列表里的顺序 = 试密码的顺序。
  · 来源函数**不许**把密码写进日志或抛出去（`observe.报` 会打码，但仍不该主动打）。
"""
from observe import 去重


def 从命令行(值们):
    """命令行 `--密码` 给的那些（可给多次）。"""
    return [str(p) for p in (值们 or []) if str(p or "").strip()]


def 从界面(界面返回):
    """界面上那个框敲的那些（一行一个）。"""
    return [str(p) for p in (界面返回 or []) if str(p or "").strip()]


def 合并(*各路):
    """把若干来源合起来**去重**（先来的排前面 = 先试）。"""
    全部 = []
    for 路 in 各路:
        全部.extend(路 or [])
    return 去重(全部)
